import assert from 'node:assert/strict';
import { pedIndex, RULES, vehicleIndex } from '../src/shared/packs';
import { CYCLE } from '../src/shared/world/traffic';
import { newDrive } from '../src/server/game/ai/driving';
import { safeToCross } from '../src/server/game/ai/pedCrossings';
import { setTask, wander } from '../src/server/game/ai/tasks';
import { seatPed, spawnPed, spawnVehicle } from '../src/server/game/factory';
import { Room } from '../src/server/room';

process.env.GRIDLOCK_DATA = 'data-smoke/ped-crossings';
const room = new Room('WALK', RULES.citySeed);
room.stop();
const w = room.world;
w.vehicles.clear();
const node = w.city.nodes.find(n => n.lights && n.segs.length === 4)!;
const y = node.y + node.wh / 2 + 1.5;
const p = spawnPed(w, pedIndex('tourist'), node.x - node.wv / 2 - 1.5, y);
const tx = node.x + node.wv / 2 + 1.5;
const ai = p.ai!;
setTask(p, 'wander');
ai.block = w.map.blockAt(p.body.x, y)!.id;
ai.tx = tx; ai.ty = y; ai.crossing = 'waiting';
const phase = (t: number) => { w.time = CYCLE - (node.id * 3.7) % CYCLE + t; };
const safe = () => safeToCross(w, p, tx, y);
phase(12);
wander(w, p, 0.3);
assert.equal(ai.crossing, 'waiting');
assert.equal(p.ctl.mx, 0);
phase(9);
assert.equal(safe(), false, 'wait on amber');
phase(1);
w.rebuildHashes();
assert(safe(), 'parallel green, clear crossing');
const car = spawnVehicle(w, vehicleIndex('sedan'), node.x, y - 12, Math.PI / 2);
car.body.vy = 8;
w.rebuildHashes();
assert.equal(safe(), false, 'approaching vehicle');
car.body.vy = -8;
assert(safe(), 'departing vehicle');
node.lights = false;
phase(12);
assert(safe(), 'safe gap at an unsignalled junction');
car.body.vy = 8;
assert.equal(safe(), false, 'yield at an unsignalled junction');
car.body.x = node.x - 9; car.body.y = y - 7; car.body.angle = 0;
car.body.vx = 9; car.body.vy = 0;
const driver = spawnPed(w, pedIndex('tourist'), car.body.x, car.body.y);
seatPed(w, driver, car, 0);
driver.ai!.drive = newDrive(w, car);
driver.ai!.drive.pts = [{ x: node.x, y: y - 7 }, { x: node.x, y: y + 4 }];
w.rebuildHashes();
assert.equal(safe(), false, 'planned turn sweeps across the crosswalk');
w.vehicles.delete(car.id); w.rebuildHashes();
wander(w, p, 0.3);
assert.equal(ai.crossing, 'walking');
node.lights = true;
wander(w, p, 0.3);
assert(p.ctl.mx > 0, 'keep walking after the light changes');
p.body.x = tx;
wander(w, p, 0.3);
assert.equal(ai.crossing, 'none', 'arrive on far sidewalk');
assert(safeToCross(w, p, tx, node.y - node.wh / 2 - 1.5), 'vertical crossing has green while horizontal is red');
p.body.x = node.x - node.wv / 2 - 1.5;
ai.crossing = 'waiting'; ai.workT = CYCLE + 3;
const corner = ai.corner;
wander(w, p, 0.3);
assert.equal(ai.crossing, 'none', 'leave a persistently blocked crossing');
assert.notEqual(ai.corner, corner);
ai.crossing = 'waiting';
setTask(p, 'flee');
assert.equal(ai.crossing, 'none', 'panic cancels the curb wait');
console.log('Pedestrian crossing checks passed');
