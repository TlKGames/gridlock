// Returning to an empty spot reports the VIN. Recognition and paint are independent of the driver's heat.
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { RULES, SERVICES, VEHICLES, pedWith } from '../src/shared/packs';
import { spawnPed, spawnVehicle, seatPed, unseatPed, removeVehicle } from '../src/server/game/factory';
import { lastOf, resumeVehicle } from '../src/server/resume';
import { clearHeat, updateWanted } from '../src/server/game/systems/wanted';
import { BEHAVIOURS } from '../src/server/game/ai/behaviours';

const dir = mkdtempSync(join(tmpdir(), 'gridlock-vin-'));
process.env.GRIDLOCK_DATA = dir;
const { Room } = await import('../src/server/room');
try {
  const room = new Room('VINS', RULES.citySeed);
  const joiner = (name: string) => {
    const pl = room.join(name, { send() {}, close() {} });
    room.stop();
    if (typeof pl === 'string') throw Error(pl);
    return pl;
  };
  const owner = joiner('Owner'), thief = joiner('Driver');
  const w = room.world, p = w.peds.get(owner.pid)!, d = w.peds.get(thief.pid)!;
  const seg = w.city.segs.find(s => s.axis === 'h' && s.x1 - s.x0 > 90)!;
  const x = seg.x0 + 30, y = seg.y0;
  const type = VEHICLES.findIndex(spec => spec.roles.includes('traffic'));
  const parked = spawnVehicle(w, type, x, y, 0, -1, { slot: 'test-bay' });
  const title = w.registry.get(parked)!;
  assert(room.census.households.some(h => title.owner === 'house:' + h.id));
  removeVehicle(w, parked, true);
  room.persist();
  const restored = new Room('VINS', RULES.citySeed).world.registry;
  const same = restored.atSlot('test-bay')!;
  assert.equal(same.owner, title.owner);
  assert.equal(restored.show(same).vin, parked.vin);
  const dealer = w.city.services.find(s => SERVICES[s.spec].verb === 'dealer')!;
  const lot = w.city.lots[dealer.lot].rect;
  const dx = (lot.x0 + lot.x1) / 2, dy = (lot.y0 + lot.y1) / 2;
  assert.equal(w.registry.get(spawnVehicle(w, type, dx, dy, 0)), undefined);
  const purchased = spawnVehicle(w, type, dx, dy, 0, -1, { owner: 'player:' + owner.ownerKey });
  assert.equal(w.registry.get(purchased)?.owner, 'player:' + owner.ownerKey);
  const car = spawnVehicle(w, type, x, y, 0, -1, { owner: 'player:' + owner.ownerKey });
  seatPed(w, p, car, 0); unseatPed(w, p);
  p.body.x = x - 30; p.body.y = y;
  seatPed(w, d, car, 0); car.body.x += 25;
  const police = spawnPed(w, pedWith('police'), car.body.x + 4, y);
  const patrol = spawnVehicle(w, type, police.body.x, y, Math.PI);
  seatPed(w, police, patrol, 0);
  const check = () => { w.rebuildHashes(); w.registry.update(); updateWanted(w, 1); };
  check(); assert.equal(thief.wanted, 0);
  p.body.x = x;
  check(); assert.equal(thief.wanted, 1);
  BEHAVIOURS.police.perceive(w, police);
  assert.equal(police.ai?.task, 'pursue');
  const heat = thief.heat; check(); assert.equal(thief.heat, heat);
  const passenger = joiner('Passenger'), rider = w.peds.get(passenger.pid)!;
  seatPed(w, rider, car, 1);
  check(); assert.equal(passenger.wanted, 0);
  unseatPed(w, rider);
  const savedSeat = lastOf(w, thief, 'VINS')!;
  assert.equal(savedSeat.vehicle?.vin, car.vin);
  const vin = car.vin;
  unseatPed(w, d);
  removeVehicle(w, car, true);
  room.persist();
  const reopened = new Room('VINS', RULES.citySeed);
  const saved = reopened.world.registry.find(vin)!;
  assert(saved.reported && saved.taken && !saved.disguised);
  assert.equal(reopened.world.registry.show(saved).vin, vin);
  const back = w.registry.show(w.registry.find(vin)!);
  resumeVehicle(w, thief, d, savedSeat, 'VINS');
  assert.equal(d.vehicle, back.id);
  assert.equal([...w.vehicles.values()].filter(v => v.vin === vin).length, 1);
  const shop = w.city.services.find(s => SERVICES[s.spec].verb === 'respray')!;
  Object.assign(back.body, shop.pad);
  thief.cash = 5000;
  w.rebuildHashes();
  assert.equal(room.econ.buy(thief, 'respray', '', shop.id), null);
  assert(w.registry.find(vin)!.reported && w.registry.find(vin)!.disguised);
  Object.assign(patrol.body, { x: back.body.x + 4, y: back.body.y });
  check(); assert.equal(thief.wanted, 0);
  unseatPed(w, d); seatPed(w, p, back, 0);
  assert(!w.registry.find(vin)!.taken && !w.registry.find(vin)!.reported);
  // A repaint made before discovery also defeats a later description-based sighting.
  unseatPed(w, p); seatPed(w, d, back, 0);
  w.registry.respray(back);
  back.body.x += 25; clearHeat(thief); check();
  assert(w.registry.find(vin)!.reported && !w.registry.hot(d, back));
  const resident = spawnPed(w, pedWith('civilian'), x, y);
  resident.resident = { id: 20, household: 8, job: null };
  const family = spawnVehicle(w, type, x, y, 0, -1, { owner: 'house:8' });
  seatPed(w, resident, family, 0); unseatPed(w, resident);
  resident.body.x = x - 30;
  seatPed(w, d, family, 0); family.body.x += 25;
  check(); assert(!w.registry.get(family)!.reported);
  resident.body.x = x;
  check(); assert(w.registry.get(family)!.reported);
  console.log('Parking discovery, police pursuit, VIN reload, respray timing and owner recovery passed.');
} finally { rmSync(dir, { recursive: true, force: true }); }
